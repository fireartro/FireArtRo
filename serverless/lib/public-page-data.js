import { getDatabase as defaultGetDatabase } from './mongodb.js';

const QUERY_TIMEOUT_MS = 5_000;
const PUBLICATION_PROJECTION = { _id: 0, revision_id: 1, published_at: 1, content: 1 };
const SUMMARY_FIELDS = [
  'id', 'slug', 'title', 'excerpt', 'category', 'cover_media_id', 'cover_alt', 'published_at', 'updated_at',
];
const ARTICLE_FIELDS = [...SUMMARY_FIELDS, 'body', 'status', 'created_at', 'version'];
const OPTIONAL_TEXT_FIELDS = ['excerpt', 'category', 'cover_media_id', 'cover_alt'];
const projectionFor = fields => ({ _id: 0, ...Object.fromEntries(fields.map(key => [key, 1])) });

export class PublicPageDataError extends Error {
  constructor(status = 503) {
    super(status === 404 ? 'Articolul nu a fost găsit.' : 'Conținutul public nu este disponibil momentan.');
    this.name = 'PublicPageDataError';
    this.status = status;
    this.statusCode = status;
  }
}

function parsePath(value) {
  if (typeof value !== 'string' || value.length > 2_048 || !/^\/(?!\/)/.test(value)
      || /[\\\x00-\x1f\x7f]/.test(value)) throw new PublicPageDataError(404);
  const pathname = value.split(/[?#]/, 1)[0].replace(/\/$/, '') || '/';
  if (pathname.startsWith('/blog/')) {
    const slug = pathname.slice('/blog/'.length);
    // Published slugs are generated by backend/blog.py::slugify_ro. Reject
    // path separators, traversal and operators before making a Mongo query.
    if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(slug) || slug.length > 200) throw new PublicPageDataError(404);
    return { pathname, slug };
  }
  if (/%|(?:^|\/)\.{1,2}(?:\/|$)/.test(pathname)) throw new PublicPageDataError(404);
  return { pathname, slug: null };
}

function publicPublication(document) {
  if (!document || typeof document.revision_id !== 'string'
      || !/^[a-z0-9][a-z0-9-]{0,79}$/i.test(document.revision_id)
      || !document.content || typeof document.content !== 'object' || Array.isArray(document.content)) {
    throw new PublicPageDataError();
  }
  const publishedAt = document.published_at instanceof Date
    ? document.published_at.toISOString() : document.published_at;
  if (typeof publishedAt !== 'string' || !Number.isFinite(Date.parse(publishedAt))) throw new PublicPageDataError();
  // The CMS publication is a validated SiteContent snapshot. Its media URLs
  // are already materialized at publish time: /api/content does not query the
  // administrative cms_media library. The renderer must apply the shared
  // normalizePublishedContent contract before serializing this snapshot.
  return { revision_id: document.revision_id, published_at: publishedAt, content: document.content };
}

function publicPost(document, fullArticle = false) {
  if (!document || document.status !== 'published') throw new PublicPageDataError();
  const fields = fullArticle ? ARTICLE_FIELDS : SUMMARY_FIELDS;
  const result = Object.fromEntries(fields.filter(key => Object.hasOwn(document, key)).map(key => [key, document[key]]));
  for (const key of OPTIONAL_TEXT_FIELDS) result[key] ??= '';
  if (fullArticle) result.version ??= 1;
  for (const key of ['id', 'slug', 'title', 'published_at', 'updated_at', ...OPTIONAL_TEXT_FIELDS,
    ...(fullArticle ? ['body', 'created_at'] : [])]) {
    if (typeof result[key] !== 'string') throw new PublicPageDataError();
  }
  if (!result.id || !result.title || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(result.slug)
      || !Number.isFinite(Date.parse(result.published_at)) || !Number.isFinite(Date.parse(result.updated_at))
      || (fullArticle && (!result.body || !Number.isSafeInteger(result.version) || result.version < 1))) {
    throw new PublicPageDataError();
  }
  return result;
}

/**
 * Public-only Mongo projection for initial HTML. Reads the current publication
 * on every call, so an Admin publish is reflected by the next page request.
 * There is deliberately no fallback to a draft, revision or checked-in copy.
 */
export function createPublicPageDataReader({ getDatabase = defaultGetDatabase } = {}) {
  return async function readPublicPageData(path) {
    const { pathname, slug } = parsePath(path);
    try {
      const db = await getDatabase();
      const document = await db.collection('site_content_publications').findOne(
        { id: 'current' }, { projection: PUBLICATION_PROJECTION, maxTimeMS: QUERY_TIMEOUT_MS },
      );
      const publication = publicPublication(document);
      let posts = [];
      let post = null;
      if (slug) {
        const document = await db.collection('blog_posts').findOne(
          { slug, status: 'published' }, { projection: projectionFor(ARTICLE_FIELDS), maxTimeMS: QUERY_TIMEOUT_MS },
        );
        if (!document) throw new PublicPageDataError(404);
        post = publicPost(document, true);
      } else if (pathname === '/' || pathname === '/blog') {
        const limit = pathname === '/' ? 3 : 100;
        const documents = await db.collection('blog_posts').find(
          { status: 'published' }, { projection: projectionFor([...SUMMARY_FIELDS, 'status']) },
        ).sort({ published_at: -1 }).limit(limit).maxTimeMS(QUERY_TIMEOUT_MS).toArray();
        posts = documents.map(document => publicPost(document));
      }
      return { publication, posts, post };
    } catch (error) {
      if (error instanceof PublicPageDataError) throw error;
      // Provider errors can contain connection strings and query details.
      // Only the generic typed status may cross the public handler boundary.
      throw new PublicPageDataError();
    }
  };
}

export const readPublicPageData = createPublicPageDataReader();
